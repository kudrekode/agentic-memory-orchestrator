"""Render one project's SQLite memory into an Obsidian vault.

SQLite stays the source of truth. Generated notes are replaced on every sync.
"""

from __future__ import annotations

import json
from pathlib import Path

from pydantic import BaseModel, Field

from src import config
from src.models import (
    Episode,
    Lesson,
    LessonStatus,
    MemoryLink,
    MemoryObjectType,
    MemoryScope,
    Project,
    SemanticMemory,
    SemanticRevision,
    SemanticStatus,
    WorkingState,
)
from src.storage import MemoryNotFoundError, SQLiteMemoryStore

MANIFEST_NAME = ".agent-memory-manifest.json"
_GENERATED_NOTICE = (
    "<!-- Generated by agent memory from SQLite. This file is replaced on sync. -->"
)
_ALIAS_UNSAFE = str.maketrans({"|": " ", "[": " ", "]": " ", "#": " ", "^": " "})


class ObsidianSyncError(ValueError):
    """The project cannot be rendered into an Obsidian vault."""


class ObsidianSyncResult(BaseModel):
    """Paths written and removed by one project sync, relative to the vault."""

    project_id: str
    vault_path: str
    written: list[str] = Field(default_factory=list)
    removed: list[str] = Field(default_factory=list)


def sync_project(
    store: SQLiteMemoryStore,
    project_id: str,
    *,
    vault_path: str | Path | None = None,
) -> ObsidianSyncResult:
    """Replace the project's generated Obsidian notes from the current store."""

    project = store.get_project(project_id)
    vault = _resolve_vault(project, vault_path)
    vault.mkdir(parents=True, exist_ok=True)
    notes = _render_project(store, project)
    return _write_notes(vault, project.id, notes)


def _resolve_vault(project: Project, vault_path: str | Path | None) -> Path:
    configured = vault_path or project.obsidian_path or config.vault_path()
    if configured is None or not str(configured).strip():
        raise ObsidianSyncError(f"no Obsidian path configured for project {project.id}")
    path = Path(str(configured)).expanduser().resolve()
    if path.exists() and not path.is_dir():
        raise ObsidianSyncError(f"Obsidian path is not a directory: {path}")
    return path


def _render_project(store: SQLiteMemoryStore, project: Project) -> dict[str, str]:
    episodes = store.list_episodes(project.id)
    semantics = store.list_semantic_memories(project.id)
    lessons = store.list_lessons(project.id)
    links = store.list_memory_links_for_project(project.id)
    revisions = {
        memory.id: store.list_semantic_revisions(memory.id) for memory in semantics
    }
    try:
        working_state = store.get_working_state(project.id)
    except MemoryNotFoundError:
        working_state = None
    titles = _titles(episodes, semantics, lessons)
    notes = {
        "Current State.md": _render_current_state(project, working_state, episodes),
        "Semantic.md": _render_semantic_index(project, semantics),
        "Lessons.md": _render_lesson_index(project, lessons),
    }
    for episode in episodes:
        notes[f"Episodes/{episode.id}.md"] = _render_episode(episode, links, titles)
    for memory in semantics:
        notes[f"Semantic/{memory.id}.md"] = _render_semantic(
            memory, revisions[memory.id], links, titles
        )
    for lesson in lessons:
        notes[f"Lessons/{lesson.id}.md"] = _render_lesson(lesson, links, titles)
    return notes


def _titles(
    episodes: list[Episode],
    semantics: list[SemanticMemory],
    lessons: list[Lesson],
) -> dict[str, str]:
    titles = {episode.id: episode.title for episode in episodes}
    titles.update(
        {memory.id: f"{memory.namespace}/{memory.key}" for memory in semantics}
    )
    titles.update({lesson.id: lesson.title for lesson in lessons})
    return titles


def _render_current_state(
    project: Project,
    state: WorkingState | None,
    episodes: list[Episode],
) -> str:
    fields: dict[str, object] = {
        "type": "working_state",
        "project_id": project.id,
        "project": project.name,
    }
    parts = ["# Current State", project.name]
    if state is None:
        parts.append("No working state is stored for this project.")
    else:
        fields["status"] = state.status.value
        fields["updated_at"] = state.updated_at.isoformat()
        if state.focus:
            parts.append(f"## Focus\n\n{state.focus}")
        parts.append(f"## Status\n\n{state.status.value}")
        for heading, items in (
            ("Known", state.known),
            ("Unknown", state.unknown),
            ("Hypotheses", state.hypotheses),
            ("Blockers", state.blockers),
            ("Next actions", state.next_actions),
            ("Active files", state.active_files),
            ("Active services", state.active_services),
        ):
            if items:
                parts.append(f"## {heading}\n\n{_bullets(items)}")
    if episodes:
        parts.append(
            "## Episodes\n\n"
            + _bullets(
                [
                    f"{_wikilink(episode.id, episode.title)} — {episode.outcome.value}"
                    for episode in episodes
                ]
            )
        )
    return _document(fields, parts)


def _render_semantic_index(project: Project, memories: list[SemanticMemory]) -> str:
    return _render_index(
        project,
        "Semantic",
        "semantic",
        "No active semantic memories.",
        memories,
        lambda memory: memory.status == SemanticStatus.ACTIVE,
        lambda memory: _wikilink(memory.id, f"{memory.namespace}/{memory.key}"),
    )


def _render_lesson_index(project: Project, lessons: list[Lesson]) -> str:
    return _render_index(
        project,
        "Lessons",
        "lessons",
        "No active lessons.",
        lessons,
        lambda lesson: lesson.status == LessonStatus.ACTIVE,
        lambda lesson: _wikilink(lesson.id, lesson.title),
    )


def _render_index(
    project, heading, collection, empty_message, records, is_active, label
) -> str:
    active = [record for record in records if is_active(record)]
    inactive = [record for record in records if not is_active(record)]
    parts = [f"# {heading}", project.name]
    if active:
        parts.append(_bullets([label(record) for record in active]))
    else:
        parts.append(empty_message)
    if inactive:
        parts.append("## Inactive\n\n" + _bullets([label(record) for record in inactive]))
    return _document(
        {
            "type": "index",
            "collection": collection,
            "project_id": project.id,
            "project": project.name,
        },
        parts,
    )


def _render_episode(
    episode: Episode, links: list[MemoryLink], titles: dict[str, str]
) -> str:
    parts = [f"# {_one_line(episode.title)}", episode.summary]
    if episode.details:
        parts.append("## Details\n\n" + _bullets([_one_line(item) for item in episode.details]))
    related = _related_lines(episode.id, links, titles)
    if related:
        parts.append("## Related\n\n" + "\n".join(related))
    return _document(
        {
            "id": episode.id,
            "type": "episode",
            "project_id": episode.project_id,
            "outcome": episode.outcome.value,
            "confidence": episode.confidence.value,
            "importance": episode.importance.value,
            "consolidation_status": episode.consolidation_status.value,
            "source": episode.source.value,
            "occurred_at": episode.occurred_at.isoformat(),
            "tags": episode.tags,
            "entities": episode.entities,
            "services": episode.services,
            "scope": _scope_mapping(episode.scope),
        },
        parts,
    )


def _render_semantic(
    memory: SemanticMemory,
    revisions: list[SemanticRevision],
    links: list[MemoryLink],
    titles: dict[str, str],
) -> str:
    parts = [f"# {_one_line(f'{memory.namespace}/{memory.key}')}", memory.statement]
    if revisions:
        lines = []
        for revision in revisions:
            lines.append(
                f"- {revision.revision_number}. {revision.change_type.value}: "
                f"{_one_line(revision.new_statement)}"
            )
            if revision.reason:
                lines.append(f"  {_one_line(revision.reason)}")
        parts.append("## Revisions\n\n" + "\n".join(lines))
    related = _related_lines(memory.id, links, titles)
    if related:
        parts.append("## Related\n\n" + "\n".join(related))
    return _document(
        {
            "id": memory.id,
            "type": "semantic",
            "project_id": memory.project_id,
            "namespace": memory.namespace,
            "key": memory.key,
            "status": memory.status.value,
            "confidence": memory.confidence.value,
            "importance": memory.importance.value,
            "current_revision": str(memory.current_revision),
            "source": memory.source.value,
            "scope": _scope_mapping(memory.scope),
        },
        parts,
    )


def _render_lesson(
    lesson: Lesson, links: list[MemoryLink], titles: dict[str, str]
) -> str:
    parts = [
        f"# {_one_line(lesson.title)}",
        "## When\n\n" + _bullets(lesson.triggers),
        f"## Do\n\n{lesson.instruction}",
        f"## Because\n\n{lesson.reason}",
    ]
    related = _related_lines(lesson.id, links, titles)
    if related:
        parts.append("## Related\n\n" + "\n".join(related))
    return _document(
        {
            "id": lesson.id,
            "type": "lesson",
            "project_id": lesson.project_id,
            "category": lesson.category.value,
            "priority": lesson.priority.value,
            "status": lesson.status.value,
            "confidence": lesson.confidence.value,
            "source": lesson.source.value,
            "scope": _scope_mapping(lesson.scope),
        },
        parts,
    )


def _related_lines(
    memory_id: str, links: list[MemoryLink], titles: dict[str, str]
) -> list[str]:
    lines = []
    for link in links:
        if link.source_id == memory_id:
            other_id = link.target_id
            other_type = link.target_type
            prefix = link.relationship.value.replace("_", " ")
        elif link.target_id == memory_id:
            other_id = link.source_id
            other_type = link.source_type
            prefix = f"{link.relationship.value.replace('_', ' ')} by"
        else:
            continue
        if other_type == MemoryObjectType.SEMANTIC_REVISION or other_id not in titles:
            lines.append(f"- {prefix} `{other_id}`")
        else:
            lines.append(f"- {prefix} {_wikilink(other_id, titles[other_id])}")
    return lines


def _document(fields: dict[str, object], parts: list[str]) -> str:
    body = "\n\n".join(part.strip() for part in parts if part and part.strip())
    return f"{_frontmatter(fields)}\n\n{_GENERATED_NOTICE}\n\n{body}\n"


def _frontmatter(fields: dict[str, object]) -> str:
    lines = ["---"]
    for key, value in fields.items():
        if value is None or value == [] or value == {}:
            continue
        lines.extend(_yaml_field(key, value, 0))
    lines.append("---")
    return "\n".join(lines)


def _yaml_field(key: str, value: object, indent: int) -> list[str]:
    pad = "  " * indent
    if isinstance(value, dict):
        rows = [f"{pad}{key}:"]
        for child_key, child_value in value.items():
            if child_value:
                rows.extend(_yaml_field(str(child_key), child_value, indent + 1))
        return rows if len(rows) > 1 else []
    if isinstance(value, list):
        rows = [f"{pad}{key}:"]
        rows.extend(f"{pad}  - {_yaml_quote(str(item))}" for item in value)
        return rows
    return [f"{pad}{key}: {_yaml_quote(str(value))}"]


def _yaml_quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _scope_mapping(scope: MemoryScope) -> dict[str, str]:
    return {key: value for key, value in scope.model_dump().items() if value}


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items)


def _one_line(text: str) -> str:
    return " ".join(text.split())


def _wikilink(memory_id: str, alias: str) -> str:
    cleaned = " ".join(alias.translate(_ALIAS_UNSAFE).split()) or memory_id
    return f"[[{memory_id}|{cleaned}]]"


def _write_notes(
    vault: Path, project_id: str, notes: dict[str, str]
) -> ObsidianSyncResult:
    previous = _read_manifest(vault)
    written = sorted(notes)
    for relative in written:
        _atomic_write(_require_inside(vault, relative), notes[relative])
    removed = []
    for relative in previous:
        if relative in notes or relative == MANIFEST_NAME:
            continue
        target = _inside_or_none(vault, relative)
        if target is None or not target.is_file():
            continue
        target.unlink()
        removed.append(relative)
        _remove_empty_parents(target.parent, vault)
    _atomic_write(vault / MANIFEST_NAME, _manifest_text(project_id, written))
    return ObsidianSyncResult(
        project_id=project_id,
        vault_path=str(vault),
        written=written,
        removed=removed,
    )


def _read_manifest(vault: Path) -> list[str]:
    path = vault / MANIFEST_NAME
    if not path.is_file():
        return []
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return []
    files = payload.get("files", [])
    if not isinstance(files, list):
        return []
    return [item for item in files if isinstance(item, str)]


def _manifest_text(project_id: str, files: list[str]) -> str:
    return json.dumps({"project_id": project_id, "files": files}, indent=2) + "\n"


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    temporary.write_text(content, encoding="utf-8")
    temporary.replace(path)


def _require_inside(vault: Path, relative: str) -> Path:
    path = _inside_or_none(vault, relative)
    if path is None:
        raise ObsidianSyncError(f"refusing to write outside the vault: {relative}")
    return path


def _inside_or_none(vault: Path, relative: str) -> Path | None:
    if not relative or relative.startswith(("/", "\\")) or ".." in Path(relative).parts:
        return None
    candidate = (vault / relative).resolve()
    vault_root = vault.resolve()
    if candidate == vault_root or not candidate.is_relative_to(vault_root):
        return None
    return candidate


def _remove_empty_parents(directory: Path, vault: Path) -> None:
    vault_root = vault.resolve()
    current = directory.resolve()
    while current != vault_root and current.is_relative_to(vault_root):
        if any(current.iterdir()):
            return
        current.rmdir()
        current = current.parent
